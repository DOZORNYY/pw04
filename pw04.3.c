#include <stdio.h>

int main(void) {
    int n, i;
    long long a;

    printf("Введите число: ");
    scanf("%d", &n);

    a = 1;
    i = 0;

    while (i < n) {
        printf("%lld ", a);
        a = a * 1000;
        ++i;
    }
    printf("\n");

    // i++ сначала возвращает значение, потом увеличивает.
    // ++i сначала увеличивает, потом возвращает.
    // В цикле разницы нет, так как i используется только для сравнения

    return 0;
}